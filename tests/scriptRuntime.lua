local Assert = require("tests.Assert")
local Engine = setmetatable({}, {__index = require("Engine")})
for _, name in ipairs({"Camera", "Sprite", "Pointer", "Rect", "Canvas"}) do Engine[name] = require("plugins.LaboEssentials.Assets." .. (name == "Rect" and "RectBounds" or name)) end
local World = require("core.World")
local tests = {}
local function add(name, fn) tests[#tests + 1] = {name = name, fn = fn} end
local function object(world, x, y) return assert(world:addLObject({transform = {x = x or 0, y = y or 0}})) end
add("LObject owns Transform and attached scripts have no separate Transform", function()
    local world = World.new(); local parent, child = object(world, 100, 50), object(world, 20, 10)
    child:attachTo(parent); local script = require("core.ScriptRuntime").attach(child, "empty", Engine.Script)
    Assert.equal(nil, child.rootComponent); Assert.equal(nil, script.transform)
    Assert.equal(120, script:getWorldTransform().x); Assert.equal(60, script:getWorldTransform().y)
    Assert.equal(child, script.owner)
end)
add("Multiple attachments of one script keep properties and runtime state independent", function()
    local class = Engine.Script:extend({properties = {speed = {type = "number", default = 10}}})
    local world = World.new(); local a, b = object(world), object(world)
    local first, second, third = require("core.ScriptRuntime").attach(a, "first", class), require("core.ScriptRuntime").attach(a, "second", class), require("core.ScriptRuntime").attach(b, "first", class)
    first.speed = 50; first.counter = 1
    Assert.equal(10, second.speed); Assert.equal(10, third.speed); Assert.equal(nil, second.counter)
    Assert.equal(50, first.properties.speed); Assert.equal(false, pcall(a.addScript, a, "first", class))
end)
add("Only defined update and draw callbacks are registered including inherited callbacks", function()
    local world = World.new(); local a = object(world)
    require("core.ScriptRuntime").attach(a, "empty", Engine.Script)
    local class = Engine.Script:extend({update = function(self, dt) self.owner.transform.x = self.owner.transform.x + dt end})
    require("core.ScriptRuntime").attach(a, "update", class:extend({})); require("core.ScriptRuntime").attach(a, "draw", Engine.Script:extend({draw = function() end}))
