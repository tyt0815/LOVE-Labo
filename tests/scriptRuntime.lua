add("Draw callbacks can disable later scripts in both renderer paths", function()
    local world = World.new(); local owner = object(world)
    local nextScript, draws = nil, 0
    require("core.ScriptRuntime").attach(owner, "first", Engine.Script:extend({draw = function() nextScript.enabled = false end}))
    nextScript = require("core.ScriptRuntime").attach(owner, "second", Engine.Script:extend({draw = function() draws = draws + 1 end}))
    local renderer = require("core.Renderer")
    renderer.drawObjects(world.lobjects, function() end, function(x, y) return x, y end, 1)
    Assert.equal(false, nextScript.enabled); Assert.equal(0, draws)
    nextScript.enabled = true
    renderer.drawWorld(world, function() end, require("core.Viewport").new(world, 0, 0, 100, 100))
    Assert.equal(false, nextScript.enabled); Assert.equal(0, draws)
    owner:getScriptByName("first").enabled = false; nextScript.enabled = true
    renderer.drawWorld(world, function() end, require("core.Viewport").new(world, 0, 0, 100, 100))
    Assert.equal(1, draws)
end)
