add("Pointer callbacks may delete their owner or their attachment", function()
    for _, removeOwner in ipairs({true, false}) do
        local world = World.new(); local a = object(world)
        require("core.ScriptRuntime").attach(a, "pointer", Engine.Pointer:extend({onPointerDown = function(self, event)
            if removeOwner then assert(event.world:removeLObject(self.owner)) else require("core.ScriptRuntime").detach(self.owner, self.id) end
            return true
        end}))
        local ok, result = world:dispatchPointer("down", 0, 0, 1)
        Assert.equal(true, ok); Assert.equal(true, result.consumed); Assert.equal(nil, next(world.pointerCaptures))
        Assert.equal(a.runtimeId, result.targets[1].runtimeId)
    end
end)
