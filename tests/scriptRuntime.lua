local Assert = require("tests.Assert")
local Engine = require("Engine")
local World = require("core.World")
local tests = {}
local function add(name, fn) tests[#tests + 1] = {name = name, fn = fn} end
local function object(world, x, y) return assert(world:addLObject({transform = {x = x or 0, y = y or 0}})) end
add("LObject owns Transform and attached scripts have no separate Transform", function()
    local world = World.new(); local parent, child = object(world, 100, 50), object(world, 20, 10)
    child:attachTo(parent); local script = child:addScript("empty", Engine.Script)
    Assert.equal(nil, child.rootComponent); Assert.equal(nil, script.transform)
    Assert.equal(120, script:getWorldTransform().x); Assert.equal(60, script:getWorldTransform().y)
    Assert.equal(child, script.owner)
end)
add("Multiple attachments of one script keep properties and runtime state independent", function()
    local class = Engine.Script:extend({properties = {speed = {type = "number", default = 10}}})
    local world = World.new(); local a, b = object(world), object(world)
    local first, second, third = a:addScript("first", class), a:addScript("second", class), b:addScript("first", class)
    first.speed = 50; first.counter = 1
    Assert.equal(10, second.speed); Assert.equal(10, third.speed); Assert.equal(nil, second.counter)
    Assert.equal(50, first.properties.speed); Assert.equal(false, pcall(a.addScript, a, "first", class))
end)
add("Only defined update and draw callbacks are registered including inherited callbacks", function()
    local world = World.new(); local a = object(world)
    a:addScript("empty", Engine.Script)
    local class = Engine.Script:extend({update = function(self, dt) self.owner.transform.x = self.owner.transform.x + dt end})
    a:addScript("update", class:extend({})); a:addScript("draw", Engine.Script:extend({draw = function() end}))
    Assert.equal(1, #a.updateScripts); Assert.equal(1, #a.drawScripts)
    assert(a:beginPlay(world)); assert(world:update(2)); Assert.equal(2, a.transform.x)
    a:removeScript("update"); assert(world:update(2)); Assert.equal(2, a.transform.x)
end)
add("beginPlay attachment is initialized exactly once without recursion", function()
    local calls = 0
    local child = Engine.Script:extend({beginPlay = function() calls = calls + 1 end})
    local parent = Engine.Script:extend({beginPlay = function(self) calls = calls + 1; self.owner:addScript("child", child) end})
    local world = World.new(); local a = object(world); a:addScript("parent", parent)
    assert(a:beginPlay(world)); assert(a:beginPlay(world)); Assert.equal(2, calls)
end)
add("Update removal and addition during callback use a stable frame boundary", function()
    local world = World.new(); local a = object(world); local calls = {}
    local added = Engine.Script:extend({update = function() calls[#calls + 1] = "added" end})
    a:addScript("first", Engine.Script:extend({update = function(self)
        calls[#calls + 1] = "first"
        if self.owner.scripts.second then self.owner:removeScript("second"); self.owner:addScript("added", added) end
    end}))
    a:addScript("second", Engine.Script:extend({update = function() error("removed callback must not run") end}))
    assert(a:beginPlay(world)); assert(world:update(0)); Assert.equal(1, #calls)
    assert(world:update(0)); Assert.equal("added", calls[3])
end)
add("Object hierarchy order precedes attachment order and empty objects receive no update call", function()
    local world = World.new(); local child, parent, empty = object(world), object(world), object(world)
    child:attachTo(parent); local calls = {}
    local class = Engine.Script:extend({update = function(self) calls[#calls + 1] = self.id end})
    parent:addScript("parent1", class); parent:addScript("parent2", class); child:addScript("child", class)
    empty.update = function() error("empty object must not update") end
    assert(parent:beginPlay(world)); assert(child:beginPlay(world)); assert(world:update(0))
    Assert.equal("parent1", calls[1]); Assert.equal("parent2", calls[2]); Assert.equal("child", calls[3])
end)
add("Camera script uses owner transform and supports designation auto fallback and letterbox", function()
    local world = World.new(); local first, second = object(world, 100, 50), object(world)
    local camera = first:addScript("camera", Engine.Camera, {viewWidth = 400, viewHeight = 200, zoom = 2})
    local other = second:addScript("camera", Engine.Camera)
    Assert.equal(camera, world:getActiveCamera()); assert(world:setActiveCamera(other)); Assert.equal(other, world:getActiveCamera())
    assert(world:setActiveCamera(nil)); Assert.equal(camera, world:getActiveCamera())
    local viewport = require("core.Viewport").new(world, 10, 20, 800, 600)
    Assert.equal(4, viewport.scale); local x, y = viewport:worldToScreen(100, 50); Assert.equal(410, x); Assert.equal(320, y)
    Assert.equal(false, viewport:containsWorldScreen(410, 30))
    first.transform.rotation, first.transform.rotationY = 30, 180
    Assert.equal(30, camera:getViewTransform().rotation); Assert.equal(nil, camera.enabled)
end)
add("Custom draw script needs no renderer inheritance and optional bounds support selection", function()
    local world = World.new(); local a = object(world); local calls = 0
    a:addScript("draw", Engine.Script:extend({draw = function() calls = calls + 1 end}))
    local renderer = require("core.Renderer")
    Assert.equal(false, renderer.hit(a, function() end, 0, 0))
    renderer.outline(a, function() end, function(x, y) return x, y end)
    renderer.draw(a, function() end, function(x, y) return x, y end, 1); Assert.equal(1, calls)
end)
add("Pointer scripts honor custom bounds hitTest and release multi-button captures", function()
    local world = World.new(); local a = object(world)
    a:addScript("shape", Engine.Rect:extend({hitTest = function(_, _, x, y) return x * x + y * y < 100 end}))
    local releases = 0
    a:addScript("pointer", Engine.Pointer:extend({onPointerDown = function() return true end, onPointerUp = function() releases = releases + 1; return true end}), {boundsSource = "shape"})
    local ok, result = world:dispatchPointer("down", 9, 9, 1); assert(ok); Assert.equal(false, result.consumed)
    assert(world:dispatchPointer("down", 0, 0, 1)); assert(world:dispatchPointer("down", 0, 0, 2))
    assert(world:dispatchPointer("up", 1000, 1000, 2)); Assert.truthy(world.pointerCaptures[1])
    assert(world:dispatchPointer("up", 1000, 1000, 1)); Assert.equal(2, releases); Assert.equal(nil, next(world.pointerCaptures))
end)
add("Canvas starts screen coordinates at the owner's Transform and child scripts inherit it", function()
    local world = World.new(); local parent, canvasObject, child = object(world, 500, 200), object(world, 10, 20), object(world, 5, 7)
    canvasObject:attachTo(parent); child:attachTo(canvasObject)
    canvasObject:addScript("canvas", Engine.Canvas)
    local rect = child:addScript("rect", Engine.Rect, {fillParent = true})
    local transform = require("core.CoordinateSpace").transform(rect)
    Assert.equal(15, transform.x); Assert.equal(27, transform.y)
    local _, _, width, height = rect:getBounds({viewport = {width = 800, height = 600}})
    Assert.equal(800, width); Assert.equal(600, height)
end)
add("Runtime callback errors are contained and invalid property schemas are rejected", function()
    local world = World.new(); local a = object(world)
    a:addScript("fail", Engine.Script:extend({update = function() error("expected error") end}))
    assert(a:beginPlay(world)); local ok, err = world:update(0); Assert.equal(false, ok); Assert.truthy(err:find("expected error", 1, true))
    Assert.equal(false, pcall(Engine.Script.extend, Engine.Script, {properties = {owner = {type = "number", default = 0}}}))
    Assert.equal(false, pcall(Engine.Script.extend, Engine.Script, {update = 1}))
end)
add("Custom pointer callbacks need no Pointer inheritance and use optional local bounds", function()
    local world = World.new(); local a = object(world); local clicks = 0
    a:addScript("custom", Engine.Script:extend({getLocalBounds = function() return -10, -10, 20, 20 end,
        onPointerDown = function() clicks = clicks + 1; return true end}))
    local ok, result = world:dispatchPointer("down", 0, 0, 1)
    Assert.equal(true, ok); Assert.equal(true, result.consumed); Assert.equal(1, clicks)
end)
add("Runtime object removal clears descendants captures and pending updates", function()
    local world = World.new(); local a, b = object(world), object(world); b:attachTo(a)
    local pointer = a:addScript("pointer", Engine.Pointer, {blockPointer = true})
    b:addScript("fail", Engine.Script:extend({update = function() error("removed child") end}))
    assert(a:beginPlay(world)); assert(b:beginPlay(world)); assert(world:dispatchPointer("down", 0, 0, 1))
    Assert.equal(pointer, world.pointerCaptures[1]); assert(world:removeLObject(a))
    Assert.equal(0, #world.lobjects); Assert.equal(nil, next(world.pointerCaptures)); assert(world:update(0))
end)
add("Removing an initializing script does not skip the next attachment", function()
    local world = World.new(); local a = object(world); local initialized = false
    a:addScript("first", Engine.Script:extend({beginPlay = function(self) self.owner:removeScript(self.id) end}))
    a:addScript("second", Engine.Script:extend({beginPlay = function() initialized = true end}))
    assert(a:beginPlay(world)); Assert.equal(true, initialized)
end)
add("Drawing tolerates removal of the current object and queued descendants", function()
    local world = World.new(); local a, b = object(world), object(world); b:attachTo(a)
    a:addScript("remove", Engine.Script:extend({draw = function() assert(world:removeLObject(a)) end}))
    b:addScript("fail", Engine.Script:extend({draw = function() error("removed draw") end}))
    local viewport = require("core.Viewport").new(world, 0, 0, 800, 600)
    require("core.Renderer").drawWorld(world, function() end, viewport)
    Assert.equal(0, #world.lobjects)
end)
add("Pointer callbacks may delete their owner or their attachment", function()
    for _, removeOwner in ipairs({true, false}) do
        local world = World.new(); local a = object(world)
        a:addScript("pointer", Engine.Pointer:extend({onPointerDown = function(self, event)
            if removeOwner then assert(event.world:removeLObject(self.owner)) else self.owner:removeScript(self.id) end
            return true
        end}))
        local ok, result = world:dispatchPointer("down", 0, 0, 1)
        Assert.equal(true, ok); Assert.equal(true, result.consumed); Assert.equal(nil, next(world.pointerCaptures))
        Assert.equal(a.runtimeId, result.targets[1].runtimeId)
    end
end)
add("Properties cannot shadow lifecycle callbacks or Script methods", function()
    for _, name in ipairs({"update", "draw", "beginPlay", "isA", "getBounds", "getWorldTransform", "onPointerDown", "new", "extend"}) do
        Assert.equal(false, pcall(Engine.Script.extend, Engine.Script, {properties = {[name] = {type = "number", default = 1}}}))
    end
end)
add("Deleting an object during initialization stops remaining callbacks", function()
    local world = World.new(); local a = object(world)
    a:addScript("remove", Engine.Script:extend({beginPlay = function(self) assert(world:removeLObject(self.owner)) end}))
    local later = a:addScript("later", Engine.Script:extend({beginPlay = function(self) self.owner.transform.x = 123 end}))
    assert(a:beginPlay(world)); Assert.equal(nil, later.hasBegunPlay); Assert.equal(nil, a.world)
    assert(a:beginPlay(world)); Assert.equal(nil, a.world)
end)
add("Draw sorting ignores pointer priority and referenced bounds sorting", function()
    local world = World.new(); local a, b = object(world), object(world)
    local source = a:addScript("source", Engine.Sprite, {sortingOrder = 50})
    local dual = a:addScript("dual", Engine.Pointer:extend({properties = {sortingOrder = {type = "number", default = 0}}, draw = function() end}),
        {boundsSource = "source", inputPriority = 10})
    local plain = b:addScript("plain", Engine.Sprite, {sortingOrder = 5})
    local Order = require("core.ScriptOrder")
    local draws = Order.entries(world.lobjects, "draw")
    Assert.equal(dual, draws[1].script); Assert.equal(plain, draws[2].script); Assert.equal(source, draws[3].script)
    local pointers = Order.entries(world.lobjects, "pointer")
    Assert.equal(10, pointers[1].priority); Assert.equal(50, pointers[1].order)
end)
return tests
