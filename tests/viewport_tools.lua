    app:textinput("12.5")
    app:keypressed("return")
    Assert.equal(12.5, view.snapSettings.translate.unit)
    for _, invalid in ipairs({"0", "-10", "nan", "1e999"}) do
        app:mousepressed(field.x + 5, field.y + 5, 1)
        app:textinput(invalid)
        app:keypressed("return")
        Assert.equal(12.5, view.snapSettings.translate.unit)
    end
