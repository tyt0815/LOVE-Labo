    Assert.equal(75, duplicate.transform.rotation)
    Assert.equal(2, duplicate.transform.scaleX)
    Assert.equal(0.5, duplicate.transform.scaleY)
    local world = assert(require("core.world").fromLevelData(loaded:toData()))
    world.lobjects[1].transform.rotation = 100
    Assert.equal(75, loaded.lobjects[1].transform.rotation)
    local legacy = assert(Level.fromData({formatVersion = 2, lobjects = {{authoringId = 1, transform = {x = 0, y = 0}}}}))
    Assert.equal(0, legacy.lobjects[1].transform.rotation)
    Assert.equal(1, legacy.lobjects[1].transform.scaleX)
    Assert.equal(nil, legacy:toData().lobjects[1].transform.rotation)
    for _, invalid in ipairs({0, -1, false, math.huge}) do
        data.lobjects[1].transform.scaleX = invalid
        Assert.equal(nil, Level.fromData(data))
        Assert.equal(nil, require("core.world").fromLevelData(data))
    end
end)

