local function run(project, command, fields)
    fields = fields or {}; fields.command, fields.project = command, project.rootPath
    local result = Cli.execute(fields)
    assert(project:rebuildAssetIndex())
    return result
end
local function script(project, name, source)
    local result = run(project, "class.create", {name = name})
    assert(Fs.writeAtomic(assert(project:resolveSourceFile(result.assetId)), source))
    return result.assetId
end
local MOVE = [[-- labo-script: script
local Move = {properties = {speed = {type = "number", default = 10, group = "Movement"},
target = {type = "object", default = false}, sibling = {type = "script", default = false},
projectile = {type = "prefab", default = false}}}
function Move.load(self) self.started = true end
function Move.update(self, dt) self.owner.transform.x = self.owner.transform.x + self.speed * dt end
return Move
]]
local function player(project)
    local source = script(project, "Move", MOVE)
    local prefab = run(project, "prefab.create", {name = "PF_Player"}).assetId
    run(project, "prefab.script.add", {prefab = prefab, source = source, script = "move"})
    return source, prefab
end
local function document(project, prefab)
    local doc = assert(require("editor.PrefabDocument").load(project, prefab))
    project.draftAssets = project.draftAssets or {}; project.draftAssets[doc.assetId] = doc
    local editor = require("editor.PrefabEditor").new(project, doc, function() project.draftRevision = (project.draftRevision or 0) + 1 end, function() end)
    return doc, editor
end
