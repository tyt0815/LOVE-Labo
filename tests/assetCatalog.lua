add("Registered and untracked asset read failures return errors without changing the catalog", function()
    for _, untracked in ipairs({false, true}) do
        local p = project(); assert(p:createEntry("Assets", "lua", "Readable", {scriptKind = "script"}))
        local id = p:getAssetId("Assets/Readable.lua")
        local reference = "Assets/Readable.lua"
        if untracked then
            assert(Fs.rename(p:resolvePath(reference), p:resolvePath("Assets/Untracked.lua")))
            reference = "Assets/Untracked.lua"
        end
        local path, read = p:resolvePath(reference), Fs.read
        local before = Fs.read(Fs.join(p.rootPath, "assets.json"))
        Fs.read = function(file) if file == path then return nil, "Injected asset read failure" end; return read(file) end
        local called, ok, err = pcall(p.rebuildAssetIndex, p)
        local opened, result, openError = pcall(require("editor.Project").open, p.rootPath)
        Fs.read = read
        assert(called, ok); Assert.equal(false, ok); Assert.equal("Injected asset read failure", err)
        assert(opened, result); Assert.equal(nil, result); Assert.equal("Injected asset read failure", openError)
        Assert.equal(before, Fs.read(Fs.join(p.rootPath, "assets.json")))
        Assert.equal(id, p:getAssetId("Assets/Readable.lua"))
    end
end)
