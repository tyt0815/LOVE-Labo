add("Projects and plugins use separate central catalogs and preserve legacy metadata IDs", function()
    local p = project(); assert(p:createEntry("Assets", "lua", "Behavior", {scriptKind = "script"}))
    local id = p:getAssetId("Assets/Behavior.lua")
    Assert.equal(nil, Fs.info(p:resolvePath("Assets/Behavior.lua.meta")))
    Assert.equal(id, assert(Json.decode(assert(Fs.read(Fs.join(p.rootPath, "assets.json"))))).assets["Assets/Behavior.lua"].id)
    local oldId = require("project.AssetId").new()
    assert(Fs.createFile(p:resolvePath("Assets/Legacy.lua"), "return {}"))
    assert(Fs.createFile(p:resolvePath("Assets/Legacy.lua.meta"), assert(Json.encode({version = 1, id = oldId, scriptKind = "script"}))))
    assert(p:rebuildAssetIndex()); Assert.equal(oldId, p:getAssetId("Assets/Legacy.lua"))
    Assert.equal(nil, Fs.info(p:resolvePath("Assets/Legacy.lua.meta")))
    assert(require("editor.PluginOperations").create(p, "Sample")); assert(require("editor.PluginOperations").apply(p, "Sample", true, true))
    local plugin = assert(Json.decode(assert(Fs.read(Fs.join(p.rootPath, "Plugins/Sample/plugin.json")))))
    Assert.equal(nil, plugin.scriptIds)
    Assert.truthy(Fs.info(Fs.join(p.rootPath, "Plugins/Sample/assets.json")))
    local pluginId = p:getAssetId("Assets/User Plugins/Sample/Sample.lua")
    assert(p:moveEntry("Assets/User Plugins/Sample/Sample.lua", "Assets/User Plugins/Sample/Renamed.lua"))
    assert(p:createEntry("Assets/User Plugins/Sample", "lua", "Sample", {scriptKind = "script"}))
    local replacementId = p:getAssetId("Assets/User Plugins/Sample/Sample.lua")
    p = assert(require("editor.Project").open(p.rootPath))
    Assert.equal(pluginId, p:getAssetId("Assets/User Plugins/Sample/Renamed.lua"))
    Assert.equal(pluginId, p.plugins.scripts.Sample.id)
    Assert.equal("Assets/Renamed.lua", p.plugins.scripts.Sample.file)
    Assert.truthy(replacementId ~= pluginId)
    Assert.equal(nil, p.assetMetadata["Assets/User Plugins/Sample/Sample.lua"].scriptName)
    Assert.truthy(p.plugins:loadScript("Sample"))
end)
