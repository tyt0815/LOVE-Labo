add("Background picker previews RGB and HEX without committing until Apply", function()
    local Color = require("editor.Color")
    local app = require("editor.EditorApp").new()
    local panel = app.previewPanel
    Assert.equal(Color.hex(Color.default()), Color.hex(panel:backgroundColor()))
    local function click(rect) app.uiRoot:mousepressed(rect.x + rect.w / 2, rect.y + rect.h / 2, 1) end
    local picker = panel:openBackgroundPicker()
    click(picker.fields[4]); app.uiRoot:textinput("#2468AC"); app.uiRoot:keypressed("return")
    Assert.equal("2468AC", Color.hex(picker.color))
    Assert.equal("2468AC", Color.hex(panel:backgroundColor()))
    Assert.equal(nil, panel.background)
    click(picker.fields[1]); app.uiRoot:textinput("256")
    Assert.equal(false, picker:submit()); Assert.truthy(picker.error)
    -- 잘못된 입력을 수정한 뒤 다시 검증한다.
    picker.text, picker.replace = "12", false
    assert(picker:commit()); Assert.equal(12, picker.color[1])
    click(picker.square); app.uiRoot:mousemoved(picker.square.x + picker.square.w, picker.square.y)
    app.uiRoot:mousereleased(picker.square.x + picker.square.w, picker.square.y, 1)
    Assert.truthy(math.abs(picker.s - 1) < 0.001); Assert.truthy(math.abs(picker.v - 1) < 0.001)
    click(picker.cancel); Assert.equal(nil, panel.background)
    Assert.equal(Color.hex(Color.default()), Color.hex(panel:backgroundColor()))
    picker = panel:openBackgroundPicker()
    click(picker.fields[4]); app.uiRoot:textinput("2468AC"); click(picker.apply)
    Assert.equal("2468AC", Color.hex(panel:backgroundColor()))
    picker = panel:openBackgroundPicker(); click(picker.reset); click(picker.apply)
    Assert.equal(nil, panel.background)
    Assert.equal(Color.hex(Color.default()), Color.hex(panel:backgroundColor()))
end)
