add("Preview Apply preserves inherited defaults and explicit colors even when equal to the theme", function()
    local p, doc = fixture(); assert(doc:save(p))
    local app = require("editor.EditorApp").new(nil, p)
    assert(app:inspectAsset("Assets/PF_Visual.prefab")); app:draw()
    local panel, Color = app.previewPanel, require("editor.Color")
    local function applyUnchanged()
        local picker = panel:openBackgroundPicker()
        local inherited = picker.useDefault
        assert(picker:submit())
        return inherited
    end
    Assert.equal(true, applyUnchanged())
    Assert.equal(nil, app.prefabDocument.data.previewBackground)
    assert(panel:setBackground(Color.default()))
    Assert.equal(false, applyUnchanged())
    Assert.equal(Color.hex(Color.default()), Color.hex(app.prefabDocument.data.previewBackground))
    local picker = panel:openBackgroundPicker()
    app.uiRoot:mousepressed(picker.reset.x + 4, picker.reset.y + 4, 1)
    assert(picker:submit())
    Assert.equal(true, applyUnchanged())
    Assert.equal(nil, app.prefabDocument.data.previewBackground)
    local Theme = require("editor.Theme")
    local previous = Theme.colors.viewportBackground
    Theme.colors.viewportBackground = {0.2, 0.4, 0.6, 1}
    local changed = Color.hex(panel:backgroundColor())
    Theme.colors.viewportBackground = previous
    Assert.equal("336699", changed)
    -- 이미지·인스턴스의 세션 배경도 기본색 상속과 명시적 지정을 구별한다.
