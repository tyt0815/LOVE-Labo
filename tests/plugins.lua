add("Plugin source proposals validate fresh bytes and plugin helpers load in editor and packaged projects", function()
    local p = project(); assert(Operations.create(p, "Images")); assert(Operations.apply(p, "Images", true, true))
    local reference = "Assets/User Plugins/Images/Images.lua"
    local original = assert(p:readSource(reference))
    assert(p.plugins:loadScript("Images"))
    local view = setmetatable({readSource = function(_, source)
        if p:getAssetReference(source) == reference then return "this is not Lua" end
        return p:readSource(source)
    end}, {__index = p})
    Assert.equal(nil, require("project.LuaScript").load(view, reference, "script"))
    local ok = pcall(require("editor.Cli").execute, {command = "class.set-source", project = p.rootPath, class = reference, source = "this is not Lua"})
    Assert.equal(false, ok); Assert.equal(original, p:readSource(reference))
    assert(p:createEntry("Assets/User Plugins/Images", "lua", "Helper", {scriptKind = "script"}))
    assert(Fs.writeAtomic(assert(p:resolveSourceFile("Assets/User Plugins/Images/Helper.lua")), "return {width = 321}"))
    local source = 'local helper = require("User Plugins.Images.Helper")\nreturn {properties = {width = {type = "number", default = helper.width}}}'
    local result = require("editor.Cli").execute({command = "class.set-source", project = p.rootPath, class = reference, source = source})
    Assert.equal(321, result.schema.width.default)
    p = assert(require("editor.Project").open(p.rootPath))
    Assert.equal(321, assert(p.plugins:loadScript("Images")).properties.width.default)
    local packaged = require("runtime.PackageProject").new({metadata = p.assetMetadata, plugins = p.plugins:export()})
    packaged.readSource = function(_, asset) return p:readSource(asset) end
    Assert.equal(321, assert(packaged.plugins:loadScript("Images")).properties.width.default)
    local level = require("editor.Level").new()
    level:addLObject(0, 0).scripts = {{id = "images", source = "Images"}}
    local output = Fs.join(p.rootPath, "Game.love")
    assert(require("editor.Export").write(p, level, output))
    Assert.truthy(assert(Fs.read(output)):find("Assets/User Plugins/Images/Helper.lua", 1, true))
end)
