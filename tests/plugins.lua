local Assert = require("tests.Assert")
local Fs = require("editor.HostFileSystem")
local Json = require("project.Json")
local Operations = require("editor.PluginOperations")
local tests = {}
local function add(name, fn) tests[#tests + 1] = {name = name, fn = fn} end
local function project()
    return assert(require("editor.Project").create(Fs.join(love.filesystem.getSourceBaseDirectory(), "build"),
        "PluginTest_" .. os.time() .. "_" .. love.math.random(100000, 999999)))
end
add("Fresh projects contain no enabled plugin scripts or default Camera", function()
    local p = project()
    Assert.equal(1, #p.plugins:scriptNames()); Assert.equal("Script", p.plugins:scriptNames()[1])
    assert(p:createEntry("Assets", "level", "L_Empty"))
    local doc = assert(require("editor.LevelDocument").load(assert(p:resolveAssetFile("Assets/L_Empty.level"))))
    Assert.equal(0, #doc.level.lobjects)
    local class, err = require("project.LuaScript").load(p, "Sprite", "script")
    Assert.equal(nil, class); Assert.truthy(err:find("disabled", 1, true))
end)
add("Plugin dependencies require confirmation and persist activation in dependency order", function()
    local p = project()
    assert(Operations.create(p, "Feature", {"LaboEssentials"}))
    local plan = assert(Operations.plan(p, "Feature", true))
    Assert.equal("LaboEssentials", plan[1]); Assert.equal("Feature", plan[2])
    Assert.equal(false, Operations.apply(p, "Feature", true, false))
    Assert.equal(nil, p.plugins.enabled.LaboEssentials)
    assert(Operations.apply(p, "Feature", true, true))
    p = assert(require("editor.Project").open(p.rootPath))
    Assert.equal(true, p.plugins.enabled.LaboEssentials); Assert.equal(true, p.plugins.enabled.Feature)
    local disabling = assert(Operations.plan(p, "LaboEssentials", false)); Assert.equal(2, #disabling)
    assert(Operations.apply(p, "LaboEssentials", false, true))
    Assert.equal(nil, p.plugins.enabled.Feature)
end)
add("Missing and circular plugin dependencies reject activation without changing settings", function()
    local p = project()
    assert(Operations.create(p, "Missing", {"Unavailable"}))
    local plan, err = Operations.plan(p, "Missing", true)
    Assert.equal(nil, plan); Assert.truthy(err:find("Unavailable", 1, true))
    assert(Operations.create(p, "First", {"Second"})); assert(Operations.create(p, "Second", {"First"}))
    plan, err = Operations.plan(p, "First", true)
    Assert.equal(nil, plan); Assert.truthy(err:find("cycle", 1, true))
    Assert.equal(nil, p.plugins.enabled.First)
end)
add("Used plugin cannot be disabled and packaged registries load only exported scripts", function()
    local p = project(); assert(Operations.apply(p, "LaboEssentials", true, true))
    assert(p:createEntry("Assets", "level", "L_Camera"))
    local ok, err = Operations.apply(p, "LaboEssentials", false, true)
    Assert.equal(false, ok); Assert.truthy(err:find("used", 1, true)); Assert.equal(true, p.plugins.enabled.LaboEssentials)
    local exported = p.plugins:export()
    Assert.equal(1, #exported.manifests); Assert.equal("LaboEssentials", exported.manifests[1].name)
    local dialog = require("editor.ui.PluginDialog").new(require("editor.EditorApp").new(nil, p))
    dialog.root:update(1 / 60)
    dialog:draw()
end)
add("Plugin CLI enables dependencies and creates a user script that loads in packaged data", function()
    local p = project(); local Cli = require("editor.Cli")
    Cli.execute({command = "plugin.create", project = p.rootPath, name = "Gameplay", dependencies = {"LaboEssentials"}})
    Cli.execute({command = "plugin.enable", project = p.rootPath, name = "Gameplay", confirm = true})
    p = assert(require("editor.Project").open(p.rootPath))
    Assert.truthy(require("project.LuaScript").load(p, "Gameplay", "script"))
    local level = require("editor.Level").new()
    local object = level:addLObject(0, 0); object.scripts = {{id = "gameplay", source = "Gameplay"}}
    Assert.truthy(require("runtime.WorldLoader").create(p, level:toData()))
    local listed = Cli.execute({command = "plugin.list", project = p.rootPath})
    Assert.equal(2, #listed.plugins)
end)
add("Enabled plugin assets mount by origin and user plugins support every asset operation", function()
    local p = project(); assert(Operations.create(p, "Gameplay")); assert(Operations.apply(p, "Gameplay", true, true))
    assert(Operations.apply(p, "LaboEssentials", true, true))
    local user, labo = "Assets/User Plugins/Gameplay", "Assets/Labo Plugins/LaboEssentials"
    Assert.truthy(p:checkedEntry(user)); Assert.truthy(p:getAssetId(user .. "/Gameplay.lua"))
    Assert.equal(false, p:createEntry(labo, "folder", "Rejected"))
    Assert.equal(false, p:moveEntry(labo .. "/Sprite.lua", "Assets/Sprite.lua"))
    assert(p:createEntry(user, "folder", "UI"))
    assert(p:createEntry(user .. "/UI", "prefab", "PF_Button"))
    assert(p:createEntry(user .. "/UI", "lua", "Behavior", {scriptKind = "script"}))
    assert(p:createEntry(user .. "/UI", "level", "L_Preview", {empty = true}))
    local id = p:getAssetId(user .. "/UI/PF_Button.prefab")
    assert(p:moveEntry(user .. "/UI/PF_Button.prefab", user .. "/UI/PF_Renamed.prefab"))
    Assert.equal(id, p:getAssetId(user .. "/UI/PF_Renamed.prefab"))
    local level = require("editor.Level").new(); level:addLObject(0, 0, id)
    Assert.truthy(require("runtime.WorldLoader").create(p, level:toData()))
    local scriptId = p:getAssetId(user .. "/Gameplay.lua")
    assert(p:moveEntry(user .. "/Gameplay.lua", user .. "/UI/Renamed.lua"))
    Assert.truthy(require("project.LuaScript").load(p, scriptId, "script"))
    Assert.truthy(require("project.LuaScript").load(p, "Gameplay", "script"))
    level.lobjects[1].scripts = {{id = "gameplay", source = scriptId}}
    local output = Fs.join(p.rootPath, "Game.love")
    assert(require("editor.Export").write(p, level, output))
    Assert.truthy(Fs.read(output):find("Assets/User Plugins/Gameplay/UI/Renamed.lua", 1, true))
    Assert.equal(nil, p:checkedEntry(user .. "/../../Escape"))
end)
add("Plugin folders are sibling browser roots and the management list scrolls only inside its panel", function()
    local p = project(); assert(Operations.create(p, "Gameplay")); assert(Operations.apply(p, "Gameplay", true, true))
    assert(Operations.apply(p, "LaboEssentials", true, true))
    local browser = require("editor.AssetBrowser").new(p)
    browser.expanded.Assets = false; browser:rebuildTree()
    Assert.equal(3, #browser.tree)
    for _, node in ipairs(browser.tree) do Assert.equal(0, node.depth) end
    for _, entry in ipairs(browser.entries) do Assert.equal(nil, p.pluginAssets.groups[entry.reference]) end
    assert(browser:openFolder("Assets/User Plugins/Gameplay"))
    Assert.equal("User Plugins", browser.breadcrumb:items()[1].label)
    assert(browser:openFolder("Assets/User Plugins")); Assert.equal(false, browser:goUp())
    local folders = require("editor.ui.FolderTree").new(p, "Assets", nil, "Assets", function() end)
    local roots = 0; for _, node in ipairs(folders.nodes) do if node.depth == 0 then roots = roots + 1 end end
    Assert.equal(3, roots)
    for _, name in ipairs({"ExtraA", "ExtraB", "ExtraC", "ExtraD", "ExtraE", "ExtraF", "ExtraG", "ExtraH"}) do assert(Operations.create(p, name)) end
    local dialog = require("editor.ui.PluginDialog").new(require("editor.EditorApp").new(nil, p))
    Assert.truthy(dialog.scrollbar.visible)
    dialog:dispatch("wheelmoved", dialog.list.x + 30, dialog.list.y + 30, -1); Assert.truthy(dialog.scroll > 0)
    local previous = dialog.scroll
    dialog:dispatch("wheelmoved", dialog.close.x + 20, dialog.close.y + 10, 1); Assert.equal(previous, dialog.scroll)
    dialog:draw()
end)
add("Browser leaf folders hide disclosure controls and remain selectable at the arrow position", function()
    local p = project()
    assert(p:createEntry("Assets", "folder", "Leaf")); assert(p:createEntry("Assets/Leaf", "lua", "Behavior", {scriptKind = "script"}))
    assert(p:createEntry("Assets", "folder", "Branch")); assert(p:createEntry("Assets/Branch", "folder", "Child"))
    local browser = require("editor.AssetBrowser").new(p); browser:setBounds(0, 0, 700, 300)
    local leafIndex
    for index, node in ipairs(browser.tree) do
        if node.reference == "Assets/Leaf" then leafIndex = index; Assert.equal(false, node.hasChildren) end
        if node.reference == "Assets/Branch" then Assert.equal(true, node.hasChildren) end
    end
    Assert.truthy(leafIndex)
    local Ui = require("editor.Ui")
    local x = browser.treeSlot.widget.x + Ui.METRICS.contentPaddingX + 14
    local y = browser.treeSlot.widget.y + (leafIndex - 1) * Ui.METRICS.treeRowHeight + Ui.METRICS.treeRowHeight / 2
    browser:handleContentMousepressed(x, y, 1); browser:dragReleased(x, y, 1)
    Assert.equal("Assets/Leaf", browser.folder); Assert.equal(nil, browser.expanded["Assets/Leaf"])
end)
