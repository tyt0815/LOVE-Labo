end)
add("Plugin dependencies expand independently and long errors scroll in a three-line area", function()
    local p = project(); assert(Operations.create(p, "Optional"))
    assert(Operations.create(p, "DisabledDependency", {"Optional"})); assert(Operations.create(p, "MissingDependency", {"Unavailable"}))
    local dialog = require("editor.ui.PluginDialog").new(require("editor.EditorApp").new(nil, p))
    Assert.equal("pluginDependencyDisabled", dialog:dependencyStatus("DisabledDependency"))
    Assert.equal("error", dialog:dependencyStatus("MissingDependency")); Assert.equal(nil, dialog:dependencyStatus("Optional"))
    local row; for _, item in ipairs(dialog.rows) do if item.name == "DisabledDependency" then row = item end end
    Assert.equal(32, row.height)
    dialog:dispatch("mousepressed", dialog.list.x + 12, dialog.list.y + row.offset + 16, 1)
    Assert.equal(true, dialog.expanded.DisabledDependency); Assert.equal(nil, p.plugins.enabled.DisabledDependency)
    dialog.error = string.rep("A long dependency error message with its resource path. ", 30); dialog:draw()
    Assert.truthy(dialog.errorScrollbar.visible); Assert.equal(54, dialog.errorBounds.h)
    local scroll = dialog.scroll
    dialog:dispatch("wheelmoved", dialog.errorBounds.x + 20, dialog.errorBounds.y + 10, -1)
    Assert.truthy(dialog.errorScroll > 0); Assert.equal(scroll, dialog.scroll)
end)
return tests
